"""Generate supabase/seed.sql from the SYNTHETIC generator (never hand-edit the output).

    python ml/make_seed.py [--end 2026-10-10T12:00:00+00:00] [--days 14] [--seed 42]

Regenerate any time; load the result in the Supabase SQL editor on an empty database.
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone

from synthetic import CAMERAS, ROOT, generate

HEADER = """-- SYNTHETIC DEMO DATA. Generated by ml/make_seed.py from ml/synthetic.py.
-- None of these sightings are real: they are made-up replay data for the demo
-- (source_kind = 'replay'). Regenerate with `python ml/make_seed.py`; do not edit by hand.
-- Run supabase/schema.sql first, then this file, on a fresh database.
"""

GUARD = """do $$ begin
  if exists (select 1 from sightings) then
    raise exception 'sightings is not empty; seed.sql is only for a fresh database';
  end if;
end $$;
"""


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def build_sql(rows: list[dict], species: list[dict]) -> str:
    out = [HEADER, GUARD]
    out.append("insert into cameras (name, location, park, status) values")
    out.append(",\n".join(f"  ({q(n)}, {q(loc)}, 'yellowstone', 'active')" for n, loc, _ in CAMERAS))
    out.append("on conflict (name) do nothing;\n")
    out.append("insert into species (common_name, scientific_name) values")
    out.append(",\n".join(f"  ({q(s['common_name'])}, {q(s['scientific_name'])})" for s in species))
    out.append("on conflict (scientific_name) do nothing;\n")
    out.append("insert into sightings (species_id, camera_id, seen_at, confidence, source_kind)")
    out.append("select s.id, c.id, v.seen_at::timestamptz, v.confidence::real, 'replay'")
    out.append("from (values")
    out.append(",\n".join(f"  ({q(r['species'])}, {q(r['camera'])}, {q(r['seen_at'])}, {r['confidence']})" for r in rows))
    out.append(") as v(scientific_name, camera, seen_at, confidence)")
    out.append("join species s on s.scientific_name = v.scientific_name")
    out.append("join cameras c on c.name = v.camera;")
    return "\n".join(out) + "\n"


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--end", default=None, help="end of the window, ISO 8601 (default: now, to the hour)")
    p.add_argument("--days", type=int, default=14)
    p.add_argument("--seed", type=int, default=42)
    a = p.parse_args()
    end = datetime.fromisoformat(a.end) if a.end else datetime.now(timezone.utc).replace(minute=0, second=0, microsecond=0)
    species = json.loads((ROOT / "worker" / "species.json").read_text())["species"]
    rows = generate(end, a.days, a.seed)
    path = ROOT / "supabase" / "seed.sql"
    path.write_text(build_sql(rows, species))
    print(f"wrote {len(rows)} SYNTHETIC sightings to {path}")


if __name__ == "__main__":
    main()
